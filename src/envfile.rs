use anyhow::{Context, Result};
use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

/// Session variables a Wayland GUI app needs when launched by `systemd --user`.
/// There is deliberately no X11 here: no DISPLAY, no XAUTHORITY.
const SESSION_KEYS: &[&str] = &[
    "WAYLAND_DISPLAY",
    "XDG_RUNTIME_DIR",
    "XDG_SESSION_ID",
    "XDG_SESSION_TYPE",
    "XDG_CURRENT_DESKTOP",
    "DBUS_SESSION_BUS_ADDRESS",
    "HOME",
    "USER",
    "LANG",
];

pub fn capture() -> BTreeMap<String, String> {
    SESSION_KEYS
        .iter()
        .filter_map(|key| {
            std::env::var(key)
                .ok()
                .filter(|value| !value.is_empty())
                .map(|value| ((*key).to_string(), value))
        })
        .collect()
}

/// Write a systemd `EnvironmentFile=` compatible file.
pub fn write(path: &Path, vars: &BTreeMap<String, String>) -> Result<()> {
    let mut out =
        String::from("# Generated by `linger env`. Run that again after starting a new session.\n");
    for (key, value) in vars {
        out.push_str(&format!("{key}=\"{}\"\n", escape(value)));
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, out).with_context(|| format!("writing {}", path.display()))
}

/// Escape a value for use inside double quotes in a systemd EnvironmentFile.
fn escape(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            other => out.push(other),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn escaping() {
        assert_eq!(escape(r#"a"b\c"#), r#"a\"b\\c"#);
        assert_eq!(escape("a\nb"), r"a\nb");
    }

    #[test]
    fn session_keys_are_wayland_only() {
        assert!(SESSION_KEYS.contains(&"WAYLAND_DISPLAY"));
        assert!(!SESSION_KEYS.contains(&"DISPLAY"));
        assert!(!SESSION_KEYS.contains(&"XAUTHORITY"));
    }
}
